# Python arithmetic operations - beginner friendly
# This exercise teaches the basic math operators in Python.

A = 10  # Store the first number.
B = 5  # Store the second number.

# Addition: used to combine values.
addition = A + B  # Add A and B.
print(f"Addition: {A} + {B} = {addition}")  # Show the sum.

# Subtraction: used to subtract one value from another.
subtraction = A - B  # Subtract B from A.
print(f"Subtraction: {A} - {B} = {subtraction}")  # Show the difference.

# Multiplication: used to repeat a value many times.
multiplication = A * B  # Multiply A by B.
print(f"Multiplication: {A} * {B} = {multiplication}")  # Show the product.

# Division: returns a decimal answer.
division = A / B  # Divide A by B.
print(f"Division: {A} / {B} = {division}")  # Show the float result.

# Floor division: removes the decimal part and keeps only the whole number.
floor_division = A // B  # Divide and keep only the whole number.
print(f"Floor Division: {A} // {B} = {floor_division}")  # Show the integer result.

# Modulus: gives the remainder after division.
modulus = A % B  # Find the remainder.
print(f"Modulus: {A} % {B} = {modulus}")  # Show the remainder.

# Summary:
# + adds
# - subtracts
# * multiplies
# / divides and keeps decimals
# // divides and removes decimals
# % gives the remainder.